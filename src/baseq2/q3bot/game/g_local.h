/*
Q2RTX: the Quake III game, as its bot AI (ai_*.c) sees it.

This stands in for Quake III's g_local.h. The bot AI reaches into its game in
a few places - g_entities[n].client->lasthurt_client, level.clients[n].sess,
the entity loop in BotAIStartFrame - so it gets a gentity_t, a gclient_t and
a level_locals_t, cut down to the fields it reads. ai_q2bridge.c fills them
from the Quake II game every frame (q3bot_iface.h q2b_snapshot); nothing
else in Quake III's game exists here. Everything below the trap_ line is
Quake III's own declarations, unchanged.
*/

